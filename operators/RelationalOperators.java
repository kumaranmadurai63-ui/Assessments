package operators;

public class RelationalOperators {
    public static void main(String[] args) {
        int a = 20;
        int b = 10;

        System.out.println("Are equal? " + (a == b));
        System.out.println("Is a greater than b? " + (a > b));
        System.out.println("Is a smaller than b? " + (a < b));
    }
}
